static const glyph_t *find_glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (size_t i = 0; i < sizeof(kFont) / sizeof(kFont[0]); i++) {
        if (kFont[i].ch == c) return &kFont[i];
    }
    return NULL; /* space and unknown characters */
}

int gfx_text_width(const char *s, int scale) {
    int n = 0;
    while (s[n]) n++;
    return n ? n * 6 * scale - scale : 0;
}

void gfx_text(int x, int y, const char *s, int scale, color_t c) {
    for (; *s; s++, x += 6 * scale) {
        const glyph_t *g = find_glyph(*s);
        if (!g) continue;
        for (int r = 0; r < 7; r++) {
            for (int col = 0; col < 5; col++) {
                if (g->row[r] & (0x10 >> col)) {
                    gfx_rect(x + col * scale, y + r * scale, scale, scale, c);
                }
            }
        }
    }
}
